// Совпадение ищем по конкретной сети и с учётом того, как в этой сети
// принято записывать адрес: у EVM регистр букв — это только контрольная
// сумма EIP-55 поверх одних и тех же байт, поэтому сравниваем без учёта
// регистра; у остальных семейств регистр значим, сравниваем как есть.
export function matchKnownContract(address, networkId, family) {
  const trimmed = String(address).trim();
  const normalize = (s) => (family === 'evm' ? s.toLowerCase() : s);
  const target = normalize(trimmed);
  return KNOWN_CONTRACTS.find((c) => c.network === networkId && normalize(c.address) === target) || null;
}

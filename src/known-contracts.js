// Небольшой список адресов, про которые заранее известно, что это адрес
// контракта токена, а не кошелька — TZ.md, раздел 5, случай «отправка на
// адрес контракта». Ключа от такого адреса нет ни у кого, независимо от
// того, что человек ответил на вопрос про тип получателя.
//
// Список работает только на точное совпадение и только в одну сторону:
// адрес совпал — уверенно исход E; адрес не совпал — про него не делается
// никакого вывода вообще, даже намёка. Список маленький и не претендует
// на полноту, поэтому трактовать отсутствие совпадения как «значит,
// кошелёк» — ошибка: короткий список читается как полная проверка,
// а это не так.
//
// Каждый адрес привязан к конкретной сети (полю `network`, id из
// src/networks.js): один и тот же набор байт в другой сети EVM может
// оказаться вообще ничем не занятым адресом или чьим-то кошельком —
// адрес контракта не привязан к семейству, он привязан к конкретному
// развёртыванию в конкретной сети.
//
// Источник каждого адреса указан как «по памяти» — интернета при
// разработке не было, точность должен подтвердить fact-lister и
// владелец до того, как эти адреса попадут в текст для пользователя.

export const KNOWN_CONTRACTS = [
  {
    address: '0xdAC17F958D2ee523a2206206994597C13D831ec7',
    network: 'ethereum',
    source: 'по памяти, не проверено в интернете: контракт токена USDT в Ethereum',
  },
  {
    address: '0x55d398326f99059fF775485246999027B3197955',
    network: 'bnb-smart-chain',
    source: 'по памяти, не проверено в интернете: контракт токена USDT в BNB Smart Chain (BEP-20)',
  },
  {
    address: 'TR7NHqjeKQxGTCi8q8ZY4pL8otSzgjLj6t',
    network: 'tron',
    source: 'по памяти, не проверено в интернете: контракт токена USDT в Tron',
  },
];

// Совпадение ищем по конкретной сети и с учётом того, как в этой сети
// принято записывать адрес: у EVM регистр букв — это только контрольная
// сумма EIP-55 поверх одних и тех же байт, поэтому сравниваем без учёта
// регистра; у остальных семейств регистр значим, сравниваем как есть.
export function matchKnownContract(address, networkId, family) {
  const trimmed = String(address).trim();
  const normalize = (s) => (family === 'evm' ? s.toLowerCase() : s);
  const target = normalize(trimmed);
  return KNOWN_CONTRACTS.find((c) => c.network === networkId && normalize(c.address) === target) || null;
}

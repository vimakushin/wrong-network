// Почему деньги могли оказаться в другой сети, здесь не повторяем: это
// уже сказано в пометке особого случая btc-bch-legacy прямо над шагами.
function bitcoinCashCrossChainSteps() {
  return [
    'Установите кошелёк, который поддерживает вторую сеть (ту, где, скорее всего, оказались деньги), и импортируйте в него ту же сид-фразу. Тот же ключ управляет этим адресом в обеих сетях независимо друг от друга.',
    'Проверьте баланс в обеих сетях по очереди — так вы увидите, в какой из них деньги на самом деле.',
  ];
}

// Есть ли для этого сочетания вообще механизм «поправить». Он есть там,
// где один и тот же адрес по-настоящему существует в нескольких сетях
// одновременно (один ключ, несколько параллельных балансов): у EVM и у
// пары Bitcoin/Bitcoin Cash с устаревшим форматом адреса. У остальных
// семейств совпадение семейства с выбранной сетью значит, что адрес и
// сеть и так подходят друг другу — чинить нечего (см. familyMatches в
// src/outcome.js: любое другое сочетание для tron/solana/ton/cosmos даёт
// исход A, а не B/C).
//
// От этого зависит и текст исходов B и C: звать человека «свяжитесь с
// владельцем, вот что ему делать» можно, только если делать есть что.
// Иначе вышло бы два взаимоисключающих сигнала подряд — «идите
// разбираться» и тут же «разбираться не в чем».
export function hasFixMechanic(facts, specialCases) {
  return facts.addressFamily === 'evm' || specialCases.includes('btc-bch-legacy');
}

// Вызывается только там, где hasFixMechanic вернула true.
function fixStepsFor(facts) {
  return facts.addressFamily === 'evm' ? evmFixSteps() : bitcoinCashCrossChainSteps();
}

// Последнего шага «решение за биржей, гарантий нет» здесь нет: ровно

export function getSteps(result) {
  const { outcome, facts, specialCases } = result;

  switch (outcome) {
    case 'A':
      return { steps: null, reason: 'Транзакция не состоялась — действовать не над чем, кроме как перепроверить, что вообще произошло.' };
    case 'E':
      return { steps: null, reason: 'Ключа от этого адреса нет ни у кого — пути вперёд не существует.' };
    case 'unknown':
      return { steps: null, reason: 'Мы не знаем, что это за адрес, — предлагать шаги значило бы угадывать.' };

    case 'B':
      return { steps: fixStepsFor(facts, specialCases) };
    case 'C':
      // TZ.md, исход C, просит приложить «ссылку на объяснение» для
      // владельца адреса. Ссылка эта — на объяснение исхода B на этой же
      // странице сервиса, которой пока не существует (интерфейс и
      // публикация — пункты 5–6 чеклиста MVP.md). Добавить её раньше,
      // чем появится сама страница, нечем: URL правится здесь же, одной
      // строкой, когда дойдём до публикации.
      if (!hasFixMechanic(facts, specialCases)) {
        return { steps: ['Адрес и сеть отправки совпадают, ошибки здесь нет. Это не ваш кошелёк — если вы не собирались отправлять именно этому получателю, единственное, что можно сделать, — написать ему и уточнить.'] };
      }
      return { steps: ['Свяжитесь с владельцем адреса и объясните, что случилось. Дальше — те же шаги, что и при своём кошельке, но их предстоит пройти ему:', ...fixStepsFor(facts, specialCases)] };
    case 'D':
      return { steps: exchangeSteps() };
    case 'F':
      return { steps: beaconChainSteps(facts) };

    default:
      throw new RangeError(`неизвестный исход: ${outcome}`);
  }
}

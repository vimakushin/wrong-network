// Семейства, где один и тот же адрес по-настоящему существует в нескольких
// сетях одновременно (один ключ, несколько параллельных балансов) — именно
// это и даёт «поправимо своими силами» в TZ.md, раздел 4, исходы B и C.
// У остальных семейств в нашей модели совпадение семейства с выбранной
// сетью означает, что адрес и сеть и так соответствуют друг другу — чинить
// нечего, см. familyMatches в src/outcome.js: там любое другое сочетание
// для tron/solana/ton/cosmos даёт исход A, а не B/C.
// Есть ли для этого сочетания вообще какой-то механизм «поправить»,
// а не просто «всё и так совпадает» (см. комментарий выше). От этого
// зависит, как звучит исход C: «свяжитесь с владельцем и вот что ему
// делать» — только если действительно есть что делать. Иначе получится,
// что мы сначала зовём человека к постороннему разбираться, а тут же
// говорим, что разбираться не в чем — два взаимоисключающих сигнала
// подряд (нашёл editor).
function hasFixMechanic(facts, specialCases) {
  return facts.addressFamily === 'evm' || specialCases.includes('btc-bch-legacy');
}

function fixStepsFor(facts, specialCases) {
  if (facts.addressFamily === 'evm') return evmFixSteps();
  if (specialCases.includes('btc-bch-legacy')) return bitcoinCashCrossChainSteps();
  return nothingToFixSteps();
}


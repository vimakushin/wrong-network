export function getSteps(result) {
  const { outcome, facts, specialCases } = result;

  switch (outcome) {
    case 'A':
      return { steps: null, reason: 'Транзакция не состоялась — действовать не над чем, кроме как перепроверить, что вообще произошло.' };
    case 'E':
      return { steps: null, reason: 'Ключа от этого адреса нет ни у кого — пути вперёд не существует.' };
    case 'unknown':
      return { steps: null, reason: 'Мы не знаем, что это за адрес, — предлагать шаги значило бы угадывать.' };

    case 'B':
      // Там, где чинить нечего, шагов нет: объяснение исхода уже говорит,
      // что проверить, а шаг «ничего делать не нужно» ему противоречил бы.
      if (!hasFixMechanic(facts, specialCases)) {
        return { steps: null, reason: 'Адрес и сеть подходят друг другу — чинить нечего.' };
      }
      return { steps: fixStepsFor(facts) };
    case 'C':
      if (!hasFixMechanic(facts, specialCases)) {
        return { steps: ['Это не ваш кошелёк — если вы не собирались отправлять именно этому получателю, единственное, что можно сделать, — написать ему и уточнить.'] };
      }
      return { steps: ['Свяжитесь с владельцем адреса и объясните, что случилось. Дальше — те же шаги, что и при своём кошельке, но их предстоит пройти ему:', ...fixStepsFor(facts)] };
    case 'D':
      return { steps: exchangeSteps() };
    case 'F':
      return { steps: beaconChainSteps(facts) };

    default:
      throw new RangeError(`неизвестный исход: ${outcome}`);
  }
}

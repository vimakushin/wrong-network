// Исход F. Конкретные адреса контрактов, версии Node.js и параметры газа
// из инструкции BNB Chain сюда сознательно не идут: они меняются со
// временем, а сервис не отслеживает изменения во внешних инструментах.
// Сам инструмент и ссылка на него, наоборот, названы прямо — см. ниже.
//
// Почему здесь есть ссылка на сторонний инструмент, хотя сервис
// принципиально не отправляет людей в «услуги по возврату»: этот запрет —
// про коммерческие фирмы, которые обещают вернуть деньги за плату, и
// среди них большинство — мошенники. Здесь — открытый бесплатный
// репозиторий разработчика самой сети, не услуга и не посредник. И если
// промолчать, человек пойдёт искать «восстановить застрявшие токены BNB
// Chain» в поиске, а вокруг такого запроса как раз и живут мошенники —
// то есть предупреждение об опасности без указания, где искать на самом
// деле, отправляет прямо в эту опасность. Назвать точный адрес
// безопаснее, чем промолчать.
//
// Ссылка проверена владельцем проекта 28 сентября 2026: репозиторий
// принадлежит организации bnb-chain, публичный, его README совпадает с
// официальной документацией BNB Chain.

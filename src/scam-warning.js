// Предупреждение о мошенниках — MVP.md, пункт 4 чеклиста, требования в
// TZ.md, раздел 6. Правило: должно быть в каждом ответе, независимо от
// исхода, включая случаи, где всё в порядке и делать ничего не надо.
//
// Поэтому getScamWarning() не принимает исход и вообще ничего не
// принимает — возвращает один и тот же текст всегда. Это не отсутствие
// заботы о том, что «текст, одинаковый везде, второй раз не читают» —
// решение сознательное, ниже почему.
//
// Варианты, которые рассматривались и отклонены:
// — смягчать текст для лёгких случаев (A, «ничего чинить не надо») —
//   прямо запрещено правилом: предупреждение нужно именно тогда, когда
//   человек расслабился и меньше всего этого ждёт, а не только когда
//   страшно;
// — усиливать текст только для исхода E — на первый взгляд разумно
//   (TZ.md сам говорит, что именно эти люди самая частая мишень), но
//   как только текст начинает зависеть от исхода, появляется код,
//   который надо помнить синхронизировать при каждой правке — история
//   про предоплату легко может остаться только в «усиленной» версии и
//   выпасть из обычной, никто не заметит сразу;
// — сокращать текст до одной фразы, чтобы меньше приедался — тогда
//   придётся выбирать, какую из двух обязательных мыслей (сид-фраза
//   и предоплата) выкинуть, а обе прямо требует TZ.md.
//
// Выбор: текст один и тот же везде, без веток по исходу — саму
// возможность «в одном месте смягчили, забыли поправить второе» это
// исключает конструктивно, а не тем, что кто-то не забудет. Единственная
// уступка «не примелькается» — текст короткий и по существу, а не
// длинный абзац: короткое повторяют осознанно, длинное проматывают.
// Про то, что самые беззащитные — это исход E, сказано внутри текста
// как факт для любого читателя, а не как отдельная ветка для E: это
// заодно и предупреждение получившим не-E не звонить и не писать
// знакомым с исходом E от имени «помощников».
export function getScamWarning() {
  return 'Никто настоящий никогда не попросит у вас сид-фразу или приватный ключ — ни поддержка, ни разработчик, ни тот, кто предлагает «помочь вернуть» деньги. Предоплата за возврат не работает никогда, сколько бы ни обещали. Чем безнадёжнее выглядит случай, тем настойчивее вокруг него предлагают такую «помощь» — если вам сказали, что средства не вернуть, будьте особенно осторожны с теми, кто в этот момент выходит на связь.';
}
